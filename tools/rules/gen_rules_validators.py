"""Compiles shared/schemas into Firestore rules validator functions.

The schemas are the source of truth for what a client may write; hand-copied enums and limits in
firestore.rules drift. This writes one function per validated shape between the GENERATED markers in
firestore.rules. Every string must be bounded (maxLength or a pattern without unbounded repeats) and every
list must be bounded (maxItems, an enum item set, or an override), or generation fails.

Usage: python3 -I tools/rules/gen_rules_validators.py          (rewrite the block)
       python3 -I tools/rules/gen_rules_validators.py --check  (exit 1 if the block is stale)
"""
import json
import re
import sys
from pathlib import Path

BEGIN = "    // BEGIN GENERATED by tools/rules/gen_rules_validators.py from shared/schemas. Do not edit by hand.\n"
END = "    // END GENERATED\n"
MAX_INDEXED_ITEMS = 4
# Enum fields kept as exact lists even in shape mode, because a wrong value changes engine behaviour.
STRICT_ENUMS = {"kind"}
# Numbers kept range-checked even in shape mode (array items such as box2d always keep their ranges).
STRICT_RANGES = {"latencyMs"}

REFS = {
    "report-reading.schema.json": "schema_ReportReading",
    "route-record.schema.json": "schema_RouteRecord",
    "camera-sighting.schema.json": "schema_CameraSighting",
    "#/$defs/CameraSightingReading": "schema_CameraSightingReading",
}


def q(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'") + "'"


def lst(xs) -> str:
    return "[" + ", ".join(q(x) for x in xs) + "]"


def bounded_pattern(p: str) -> bool:
    return not re.search(r"[*+]|\{\d+,\}", p)


def value_check(s: dict, ref: str, overrides: dict, shape: bool = False) -> str:
    if "$ref" in s:
        if s["$ref"] not in REFS:
            raise ValueError(f"no validator for $ref {s['$ref']}")
        return f"{REFS[s['$ref']]}({ref})"
    if "anyOf" in s:
        branches = s["anyOf"]
        nullable = any(b.get("type") == "null" for b in branches)
        rest = [b for b in branches if b.get("type") != "null"]
        inner = " || ".join(value_check(b, ref, overrides, shape) for b in rest)
        return f"({ref} == null || {inner})" if nullable else f"({inner})"
    if "enum" in s:
        values = [v for v in s["enum"] if v is not None]
        if shape and values and all(isinstance(v, str) for v in values) and ref.rsplit(".", 1)[-1] not in STRICT_ENUMS:
            # Bounded by type and length only: a list literal per enum costs rules expressions that the
            # heaviest events cannot afford; clients and engines enforce these values themselves.
            check = f"({ref} is string && {ref}.size() <= {max(len(v) for v in values)})"
        else:
            check = f"({ref} in {lst(values)})"
        return f"({ref} == null || {check})" if None in s["enum"] else check
    t = s.get("type")
    if isinstance(t, list):
        others = [x for x in t if x != "null"]
        if len(others) != 1:
            raise ValueError(f"unsupported type list {t}")
        inner = value_check({**s, "type": others[0]}, ref, overrides, shape)
        return f"({ref} == null || {inner})" if "null" in t else inner
    parts: list[str]
    if t == "string":
        parts = [f"{ref} is string"]
        if "minLength" in s:
            parts.append(f"{ref}.size() >= {s['minLength']}")
        if "maxLength" in s:
            parts.append(f"{ref}.size() <= {s['maxLength']}")
        if "pattern" in s:
            if "maxLength" not in s and not bounded_pattern(s["pattern"]):
                raise ValueError(f"unbounded string at {ref}")
            parts.append(f"{ref}.matches({q(s['pattern'])})")
        elif "maxLength" not in s:
            raise ValueError(f"unbounded string at {ref}")
    elif t in ("integer", "number"):
        parts = [f"{ref} is {'int' if t == 'integer' else 'number'}"]
        if shape and ref.rsplit(".", 1)[-1] not in STRICT_RANGES:
            # A number cannot grow; its range is enforced by clients and engines, and the heaviest events
            # cannot afford every comparison under the 1,000-expression limit.
            return "(" + parts[0] + ")"
        if "minimum" in s:
            parts.append(f"{ref} >= {q(s['minimum'])}")
        if "maximum" in s:
            parts.append(f"{ref} <= {q(s['maximum'])}")
    elif t == "boolean":
        parts = [f"{ref} is bool"]
    elif t == "null":
        return f"({ref} == null)"
    elif t == "object":
        return object_check(s, ref, overrides, shape=shape)
    elif t == "array":
        return array_check(s, ref, overrides, shape)
    else:
        raise ValueError(f"unsupported schema at {ref}: {json.dumps(s)[:80]}")
    return "(" + " && ".join(parts) + ")"


def array_check(s: dict, ref: str, overrides: dict, shape: bool = False) -> str:
    items = s.get("items", {})
    parts = [f"{ref} is list"]
    if "enum" in items:
        cap = s.get("maxItems", len(items["enum"]))
        parts += [f"{ref}.size() <= {cap}", f"{ref}.hasOnly({lst(items['enum'])})"]
    elif shape and items.get("type") == "string" and "maxLength" in items and "maxItems" in s:
        # Bounded by count and joined length; join fails (so the rule denies) if an item is not a string.
        n = s["maxItems"]
        parts += [f"{ref}.size() <= {n}", f"{ref}.join('').size() <= {n * items['maxLength']}"]
        return "(" + " && ".join(parts) + ")"
    elif "maxItems" in s and s["maxItems"] <= MAX_INDEXED_ITEMS:
        n = s["maxItems"]
        parts.append(f"{ref}.size() == {n}" if s.get("minItems") == n else f"{ref}.size() <= {n}")
        for i in range(n):
            check = value_check(items, f"{ref}[{i}]", overrides, False)
            parts.append(check if s.get("minItems", 0) > i else f"({ref}.size() < {i + 1} || {check})")
        return "(" + " && ".join(parts) + ")"
    else:
        raise ValueError(f"unbounded list at {ref}")
    if s.get("minItems"):
        parts.append(f"{ref}.size() >= {s['minItems']}")
    return "(" + " && ".join(parts) + ")"


def object_parts(s: dict, ref: str, overrides: dict, partial: bool = False, shape: bool = False) -> list[str]:
    if s.get("additionalProperties") is not False:
        raise ValueError(f"object at {ref} must set additionalProperties false")
    props = s.get("properties", {})
    required = s.get("required", [])
    if shape and not partial and set(required) == set(props):
        # Every check below reads its key, and reading a missing key is an error, which denies; with the size
        # fixed at n that pins the exact key set without a list literal (1,000-expression limit).
        parts = [f"{ref} is map", f"{ref}.size() == {len(props)}"]
        for key, sub in props.items():
            parts.append(overrides[key](f"{ref}.{key}") if key in overrides else value_check(sub, f"{ref}.{key}", {}, shape))
        return parts
    parts = [f"{ref} is map", f"{ref}.keys().hasOnly({lst(list(props))})"]
    if required and not partial:
        # Every key required: a size check replaces hasAll and its second list literal (1,000-expression limit).
        parts.append(f"{ref}.size() == {len(props)}" if set(required) == set(props) else f"{ref}.keys().hasAll({lst(required)})")
    for key, sub in props.items():
        kref = f"{ref}.{key}"
        check = overrides[key](kref) if key in overrides else value_check(sub, kref, {}, shape)
        parts.append(check if (key in required and not partial) else f"(!({q(key)} in {ref}) || {check})")
    return parts


def object_check(s: dict, ref: str, overrides: dict, partial: bool = False, shape: bool = False) -> str:
    return "(" + " && ".join(object_parts(s, ref, overrides, partial, shape)) + ")"


def function(name: str, s: dict, overrides: dict | None = None, partial: bool = False, shape: bool = False) -> str:
    body = "\n        && ".join(object_parts(s, "m", overrides or {}, partial, shape))
    return f"    function {name}(m) {{\n      return {body};\n    }}\n"


def render(repo: Path) -> str:
    sch = lambda f: json.loads((repo / "shared/schemas" / f).read_text())
    event = sch("event.schema.json")
    position = next(b for b in event["properties"]["position"]["anyOf"] if b.get("type") == "object")
    shared = sch("subject-profile.schema.json")["$defs"]["SharedProfile"]
    note_ids = json.loads((repo / "shared/constants/approach-notes.json").read_text())["order"]
    notes = {"approachNoteIds": lambda r: f"({r} is list && {r}.size() <= {len(note_ids)} && {r}.hasOnly({lst(note_ids)}))"}
    return BEGIN + "\n".join([
        function("schema_Position", position, shape=True),
        "    // Event-carried shapes (shape mode): numeric ranges, per-item checks and the kind enum as in the schema;\n"
        "    // other string enums bounded by length, and all-required key sets pinned by size, to stay under the\n"
        "    // 1,000-expression limit per request.\n"
        + function("schema_ReportReading", sch("report-reading.schema.json"), shape=True),
        function("schema_RouteRecord", sch("route-record.schema.json"), shape=True),
        function("schema_CameraSighting", sch("camera-sighting.schema.json"), shape=True),
        function("schema_CameraSightingReading", event["$defs"]["CameraSightingReading"], shape=True),
        "    // profile/shared may be written in parts: every key present is checked, none is required.\n"
        + function("schema_SharedProfile", shared, notes, partial=True),
    ]) + END


def main(argv: list[str]) -> int:
    repo = Path(__file__).resolve().parents[2]
    rules = repo / "firestore.rules"
    text = rules.read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        print("gen_rules_validators: firestore.rules needs exactly one GENERATED block", file=sys.stderr)
        return 1
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    new = head + render(repo) + tail
    if "--check" in argv:
        if new != text:
            print("gen_rules_validators: the GENERATED block in firestore.rules is stale; run the generator", file=sys.stderr)
            return 1
        print("gen_rules_validators: block is current")
        return 0
    rules.write_text(new)
    print("gen_rules_validators: block written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
